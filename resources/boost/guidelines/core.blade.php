## @javaabu/i18n

- This project translates strings in JavaScript with `@javaabu/i18n`, which has the same `__()`, `trans()` and `trans_choice()` as Laravel. Don't add another translation library.
- Always activate the `javaabu-i18n` skill when adding user-facing text to JS, or working with translations, locales or RTL in JS.
